using System.Globalization;
using System.Text;
using FactoryLayout.Core;

CultureInfo.DefaultThreadCurrentCulture = CultureInfo.InvariantCulture;
CultureInfo.CurrentCulture = CultureInfo.InvariantCulture;

const string Usage = """
factory-layout — route, draw and benchmark factory layouts without CAD

  route <layout.json> [--optimize] [--svg out.svg] [--out routed.json]
        Validate, route the conveyor, print metrics; optionally draw a blueprint
        and write the routed layout (components + conveyor modules + metrics).
  bench [--n 300] [--seed 1] [--out docs/results/bench.md]
        Random valid layouts at several sizes: routing success and time, fixed
        process order against the order the tool picks.
""";

if (args.Length == 0) { Console.WriteLine(Usage); return 1; }
try
{
    return args[0] switch
    {
        "route" => Route(args.Skip(1).ToArray()),
        "bench" => Bench(args.Skip(1).ToArray()),
        _ => Fail(Usage),
    };
}
catch (Exception e) when (e is FormatException or IOException)
{
    Console.Error.WriteLine("error: " + e.Message);
    return 1;
}

static int Fail(string msg) { Console.Error.WriteLine(msg); return 1; }

static string? Opt(string[] a, string name) { int i = Array.IndexOf(a, name); return i >= 0 && i + 1 < a.Length ? a[i + 1] : null; }

static int Route(string[] a)
{
    if (a.Length == 0) return Fail("route: give a layout.json");
    var layout = LayoutJson.Read(File.ReadAllText(a[0]));
    var issues = LayoutValidator.Validate(layout);
    foreach (var i in issues) Console.WriteLine($"  {i}");

    var route = ConveyorRouter.Route(layout, new RouteOptions { OptimizeOrder = a.Contains("--optimize") });
    if (route.Success)
    {
        var problems = RouteChecker.Check(layout, route.Cells, route.StationOrder);
        var m = LayoutMetrics.Of(layout, route);
        Console.WriteLine($"{layout.Name}: {layout.Width}x{layout.Height} cells, {layout.Components.Count} components");
        Console.WriteLine($"  conveyor {m.ConveyorLengthM:0.0} m, {m.Straights} straight / {m.Lefts} left / {m.Rights} right");
        Console.WriteLine($"  order IN -> {string.Join(" -> ", route.StationOrder)} -> OUT ({route.OrderMethod}, {route.OrdersTried} tried)");
        Console.WriteLine($"  CAD instances {m.CadInstances}, floor use {m.FloorUse:P0}, routed in {route.ElapsedMs:0.0} ms");
        Console.WriteLine(problems.Count == 0 ? "  independent check: OK" : "  independent check FAILED: " + string.Join("; ", problems));
    }
    else Console.WriteLine($"  not routed: {route.Failure}");

    var svg = Opt(a, "--svg");
    if (svg != null) { File.WriteAllText(svg, BlueprintSvg.Render(layout, route, issues)); Console.WriteLine($"  blueprint -> {svg}"); }
    var outp = Opt(a, "--out");
    if (outp != null) { File.WriteAllText(outp, LayoutJson.Write(layout, route)); Console.WriteLine($"  layout -> {outp}"); }
    return route.Success ? 0 : 2;
}

static int Bench(string[] a)
{
    int n = int.Parse(Opt(a, "--n") ?? "300");
    int seed0 = int.Parse(Opt(a, "--seed") ?? "1");
    var outPath = Opt(a, "--out");

    var configs = new (string name, int w, int h, int robots, int drills, int xrays, int pillars)[]
    {
        ("small", 12, 8, 1, 1, 1, 2),
        ("medium", 14, 10, 2, 1, 1, 3),
        ("large", 20, 15, 4, 2, 1, 6),
    };
    var modes = new (string name, RouteOptions opt)[]
    {
        ("greedy, fixed order", new RouteOptions { Branching = 1 }),
        ("backtracking, fixed order", new RouteOptions()),
        ("backtracking, tool picks order", new RouteOptions { OptimizeOrder = true }),
    };

    var md = new StringBuilder();
    md.AppendLine("# Routing benchmark");
    md.AppendLine();
    md.AppendLine($"Generated by `factory-layout bench --n {n} --seed {seed0}`. Each row routes the same {n} random");
    md.AppendLine("layouts (valid by construction: no overlaps, envelopes clear, ends free). The stations' process");
    md.AppendLine("order is random, which is harder than a real line drawn in process order. Every successful route");
    md.AppendLine("is re-checked by `RouteChecker`; the last column counts routes it rejected.");
    md.AppendLine();
    md.AppendLine("| layout | mode | routed | median ms | max ms | mean conveyor m | mean turns | rejected |");
    md.AppendLine("|---|---|---:|---:|---:|---:|---:|---:|");

    foreach (var cfg in configs)
    {
        var layouts = Enumerable.Range(seed0, n)
            .Select(s => LayoutGenerator.Random(s, cfg.w, cfg.h, cfg.robots, cfg.drills, cfg.xrays, cfg.pillars)).ToList();
        foreach (var mode in modes)
        {
            var times = new List<double>(); int ok = 0, rejected = 0; double len = 0, turns = 0;
            foreach (var l in layouts)
            {
                var r = ConveyorRouter.Route(l, mode.opt);
                times.Add(r.ElapsedMs);
                if (!r.Success) continue;
                ok++;
                if (RouteChecker.Check(l, r.Cells, r.StationOrder).Count > 0) rejected++;
                var m = LayoutMetrics.Of(l, r);
                len += m.ConveyorLengthM; turns += m.Turns;
            }
            times.Sort();
            string label = $"{cfg.name} {cfg.w}×{cfg.h}, {cfg.robots}R {cfg.drills}D {cfg.xrays}X {cfg.pillars}P";
            md.AppendLine($"| {label} | {mode.name} | {ok}/{n} ({100.0 * ok / n:0}%) | {times[times.Count / 2]:0.0} | {times[^1]:0} | {(ok > 0 ? len / ok : 0):0.0} | {(ok > 0 ? turns / ok : 0):0.0} | {rejected} |");
            Console.WriteLine($"{label,-36} {mode.name,-32} {ok,4}/{n}  median {times[times.Count / 2]:0.0} ms  max {times[^1]:0} ms  rejected {rejected}");
        }
    }

    md.AppendLine();
    md.AppendLine($"Machine: {Environment.ProcessorCount} logical cores, .NET {Environment.Version}, Release build.");
    if (outPath != null)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outPath))!);
        File.WriteAllText(outPath, md.ToString());
        Console.WriteLine($"-> {outPath}");
    }
    return 0;
}
